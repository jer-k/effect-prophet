/** Source path of the generated per-country import map. */
export const countryHolidayImportsPath = "src/internal/country-holiday-imports.ts";

const countryFilePattern = /^countries\/[A-Z]{2}\.json$/u;

/**
 * Render one static JSON-module import per catalog country.
 *
 * Bundlers leave a variable import path inside `node_modules` unresolved (Vite by default), so
 * each country gets a literal path that every bundler can split into its own chunk.
 *
 * @param countries - The calendar manifest's or catalog's country entries.
 * @throws Error when a file name is not the country's own two-letter calendar file.
 */
export const renderCountryHolidayImports = (
  countries: Readonly<Record<string, { readonly file: string }>>,
): string => {
  const entries = Object.entries(countries)
    .sort(([left], [right]) => (left < right ? -1 : 1))
    .map(([country, { file }]) => {
      if (!countryFilePattern.test(file) || file !== `countries/${country}.json`) {
        throw new Error(`Unexpected country calendar file for ${country}: ${file}`);
      }

      return `  ["${country}", () => import("../../calendars/${file}", { with: { type: "json" } })],\n`;
    });

  return [
    "// Generated by tools/generate-country-holiday-imports.ts from calendars/manifest.json; do not edit.\n",
    "\n",
    "/** Import one bundled country calendar file as a JSON module. */\n",
    "export type CountryHolidayFileImport = () => Promise<{ readonly default: unknown }>;\n",
    "\n",
    "/** One literal import per bundled country, so bundlers emit each calendar as its own chunk. */\n",
    "export const countryHolidayImports: ReadonlyMap<string, CountryHolidayFileImport> = new Map<\n",
    "  string,\n",
    "  CountryHolidayFileImport\n",
    ">([\n",
    ...entries,
    "]);\n",
  ].join("");
};
